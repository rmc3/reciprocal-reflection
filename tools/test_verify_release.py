"""Offline regression tests for release packaging, not model performance."""
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
SPEC = importlib.util.spec_from_file_location(
    "release_verifier", Path(__file__).with_name("verify_release.py"))
VERIFIER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(VERIFIER)


class ReleaseVerificationTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.old_root = VERIFIER.ROOT
        self.addCleanup(setattr, VERIFIER, "ROOT", self.old_root)
        VERIFIER.ROOT = self.root
        self.write("README.md", "# Example\n\nSee [record](record.txt).\n")
        self.write("record.txt", "Preserved fixture.\n")
        record_hash = VERIFIER.digest(self.root / "record.txt")
        self.write("EXPORT-MANIFEST.json", json.dumps({
            "files": [{"export": "record.txt", "export_sha256": record_hash}]
        }) + "\n")
        self.freeze()

    def write(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)

    def freeze(self):
        lines = []
        for path in sorted(self.root.rglob("*")):
            if (path.is_file() and path.name != "SHA256SUMS"
                    and not VERIFIER.excluded(path)):
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                lines.append(f"{digest}  {path.relative_to(self.root)}")
        self.write("SHA256SUMS", "\n".join(lines) + "\n")

    def check(self):
        with contextlib.redirect_stdout(io.StringIO()) as output:
            VERIFIER.verify()
        return json.loads(output.getvalue())

    def test_pristine_snapshot(self):
        self.assertEqual(self.check()["historical_copies_checked"], 1)

    def test_git_directory_and_bytecode_are_ignored(self):
        self.write(".git/config", "Local repository metadata.\n")
        self.write(".git/metadata.md", "[Not content](missing.txt)\n")
        self.write("__pycache__/example.pyc", "Generated bytecode.\n")
        self.write("tools/cache.pyc", "Generated bytecode.\n")
        self.assertEqual(self.check()["files_hashed"], 3)

    def test_git_worktree_metadata_file_is_ignored(self):
        self.write(".git", "gitdir: local-worktree-metadata\n")
        self.assertEqual(self.check()["files_hashed"], 3)

    def test_unexpected_content_is_rejected(self):
        self.write("unlisted.txt", "Not in this edition.\n")
        with self.assertRaisesRegex(ValueError, "unexpected file"):
            self.check()

    def test_changed_content_is_rejected(self):
        self.write("record.txt", "Changed fixture.\n")
        with self.assertRaisesRegex(ValueError, "Hash mismatch"):
            self.check()

    def test_missing_content_is_rejected(self):
        (self.root / "record.txt").unlink()
        with self.assertRaisesRegex(ValueError, "Invalid manifest path"):
            self.check()

    def test_duplicate_entry_is_rejected(self):
        manifest = (self.root / "SHA256SUMS").read_text()
        self.write("SHA256SUMS", manifest + manifest.splitlines()[0] + "\n")
        with self.assertRaisesRegex(ValueError, "Duplicate manifest entry"):
            self.check()

    def test_broken_relative_link_is_rejected(self):
        self.write("README.md", "# Example\n\nSee [record](missing.txt).\n")
        self.freeze()
        with self.assertRaisesRegex(ValueError, "Broken or escaping local link"):
            self.check()

    def test_historical_hash_survives_new_package_checksums(self):
        self.write("record.txt", "Changed fixture.\n")
        self.freeze()
        with self.assertRaisesRegex(ValueError, "Historical export mismatch"):
            self.check()

    def test_generated_metadata_cannot_be_declared_as_content(self):
        self.write(".git/config", "Metadata.\n")
        manifest = (self.root / "SHA256SUMS").read_text()
        digest = VERIFIER.digest(self.root / ".git/config")
        self.write("SHA256SUMS", manifest + f"{digest}  .git/config\n")
        with self.assertRaisesRegex(ValueError, "Invalid manifest path"):
            self.check()


if __name__ == "__main__":
    unittest.main()
